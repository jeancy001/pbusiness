import { ObjectId, type Collection, type Filter } from "mongodb"
import { getDb } from "./mongodb"
import type { UserDoc } from "./models"
import type { LocalizedText } from "@/lib/mock-data"
import type { AiTrack } from "@/lib/lms/catalog"

// ============================================================
// LMS COLLECTIONS
//
// Course metadata, progress, live sessions and certificates
// live in MongoDB. Lesson media (videos, PDFs) live in the
// Supabase Storage bucket and are referenced by storagePath.
// ============================================================

export type LessonType = "video" | "text" | "live"

export interface LessonDoc {
  _id?: ObjectId
  formationSlug: string
  title: string
  type: LessonType
  order: number
  /** Markdown/plain text body for written lessons. */
  body?: string
  /** Object path inside the Supabase course bucket. */
  storagePath?: string
  durationMin?: number
  /** Linked live session for "live" lessons. */
  liveSessionId?: string
  createdBy: string
  createdAt: Date
}

export interface LessonProgressDoc {
  _id?: ObjectId
  userId: string
  formationSlug: string
  lessonId: string
  completedAt: Date
}

export type LiveStatus = "scheduled" | "live" | "ended"

export interface LiveSessionDoc {
  _id?: ObjectId
  formationSlug: string
  teacherId: string
  topic: string
  startAt: Date
  durationMin: number
  status: LiveStatus
  /** One-to-one session: only this student (plus the teacher) can join. */
  privateFor?: string
  /** Live request that created this session. */
  requestId?: string
  createdAt: Date
}

/**
 * A student asks their teacher for a private live session, or the teacher
 * invites a student. pending → accepted (a private session is created) | declined | cancelled
 */
export type LiveRequestStatus = "pending" | "accepted" | "declined" | "cancelled"

export interface LiveRequestDoc {
  _id?: ObjectId
  formationSlug: string
  studentId: string
  studentName: string
  teacherId: string
  teacherName: string
  requestedBy: "student" | "teacher"
  topic: string
  message?: string
  proposedAt: Date
  durationMin: number
  status: LiveRequestStatus
  liveSessionId?: string
  createdAt: Date
  respondedAt?: Date
}

export interface AttendanceDoc {
  _id?: ObjectId
  sessionId: string
  userId: string
  userName: string
  role: "host" | "attendee"
  /** Current browser tab in the WebRTC room ("<userId>:<random>"). */
  peerId?: string
  joinedAt: Date
  lastSeenAt: Date
  leftAt?: Date
  /** Accumulated from client heartbeats while the user is in the meeting. */
  secondsPresent: number
}

export interface ExamQuestion {
  id: string
  prompt: string
  options: string[]
  answerIndex: number
}

export interface ExamDoc {
  _id?: ObjectId
  formationSlug: string
  questions: ExamQuestion[]
  passScore: number
  source: "teacher" | "ai"
  updatedAt: Date
}

export interface ExamAttemptDoc {
  _id?: ObjectId
  userId: string
  formationSlug: string
  score: number
  passed: boolean
  createdAt: Date
}

export interface CertificateDoc {
  _id?: ObjectId
  code: string
  userId: string
  studentName: string
  formationSlug: string
  formationTitle: LocalizedText
  teacherName?: string
  score: number
  paymentReference: string
  issuedAt: Date
}

export interface AiModuleAccessDoc {
  _id?: ObjectId
  userId: string
  moduleSlug: string
  paymentReference: string
  createdAt: Date
  /** Set when the learner marks the module as finished. */
  completedAt?: Date
}

/** AI Academy course created by an admin; its syllabus is generated by AI. */
export interface AiTrackDoc extends AiTrack {
  _id?: ObjectId
  hidden?: boolean
  createdBy: string
  createdAt: Date
}

/**
 * requested → (admin sends) processing → paid | failed
 * requested → rejected (by admin) / cancelled by teacher
 * Failed and rejected payouts return to the teacher's available balance.
 */
export type PayoutStatus = "requested" | "approved" | "processing" | "paid" | "failed" | "rejected"

export interface PayoutDoc {
  _id?: ObjectId
  /** "platform" = admin withdrawal of platform revenue; default is a teacher payout. */
  kind?: "teacher" | "platform"
  /** Teacher (or, for platform withdrawals, the admin who withdrew). */
  teacherId: string
  teacherName: string
  /** Amount deducted from the teacher's balance. */
  amountUsd: number
  feeRate: number
  feeUsd: number
  /** What the teacher actually receives. */
  netUsd: number
  country: string
  method: string
  mobile: string
  status: PayoutStatus
  /** Swychr transaction_id (stored upper case by Swychr). */
  providerReference?: string
  /** Last status reported by Swychr: PENDING, PROCESSING, SUCCESS, FAILED, REFUNDED. */
  providerStatus?: string
  /** Net amount actually sent, in the destination currency. */
  amountLocal?: number
  currency?: string
  fxRate?: number
  sentAt?: Date
  note?: string
  reviewedBy?: string
  createdAt: Date
  updatedAt: Date
}

/** WebRTC signaling message (offer / answer / ICE candidate), expired by TTL. */
export interface RtcSignalDoc {
  _id?: ObjectId
  sessionId: string
  from: string
  to: string
  type: "offer" | "answer" | "candidate" | "bye"
  payload: unknown
  createdAt: Date
}

async function col<T extends object>(name: string): Promise<Collection<T>> {
  return (await getDb()).collection<T>(name)
}

export const lessons = () => col<LessonDoc>("lessons")
export const lessonProgress = () => col<LessonProgressDoc>("lesson_progress")
export const liveSessions = () => col<LiveSessionDoc>("live_sessions")
export const liveRequests = () => col<LiveRequestDoc>("live_requests")
export const attendance = () => col<AttendanceDoc>("attendance")
export const exams = () => col<ExamDoc>("exams")
export const examAttempts = () => col<ExamAttemptDoc>("exam_attempts")
export const certificates = () => col<CertificateDoc>("certificates")
export const aiModuleAccess = () => col<AiModuleAccessDoc>("ai_module_access")
export const aiTracksCol = () => col<AiTrackDoc>("ai_tracks")
export const payouts = () => col<PayoutDoc>("payouts")
export const rtcSignals = () => col<RtcSignalDoc>("rtc_signals")

// UserDoc types _id as string, but Mongo stores ObjectIds.
export function byUserId(id: string): Filter<UserDoc> {
  return { _id: toObjectId(id) } as unknown as Filter<UserDoc>
}

export function toObjectId(id: string): ObjectId | null {
  return ObjectId.isValid(id) ? new ObjectId(id) : null
}
