"use client"

import { useState, useTransition } from "react"
import Link from "next/link"
import { useRouter } from "next/navigation"
import { Bot, Eye, EyeOff, ImagePlus, Loader2, Sparkles, Trash2 } from "lucide-react"

import { useI18n } from "@/lib/i18n/context"
import { localize } from "@/lib/mock-data"
import { AI_COURSE_PRICE_USD, aiModuleSlug, type AiTrackKind } from "@/lib/lms/catalog"
import type { AiTrackView } from "@/lib/lms/ai-tracks"
import { createAiCourseAction, deleteAiCourseAction, regenerateAiCoverAction, setAiCourseVisibilityAction } from "@/lib/lms/actions"
import { TrackCover, TrackMark } from "@/components/lms/track-cover"
import { DashboardShell } from "@/components/dashboard/dashboard-shell"
import { adminNav } from "@/components/dashboard/admin-dashboard"
import { Field, FormError, Panel, selectClass } from "@/components/lms/ui"
import { Badge } from "@/components/ui/badge"
import { Button } from "@/components/ui/button"
import { Input } from "@/components/ui/input"
import { Textarea } from "@/components/ui/textarea"
import { cn } from "@/lib/utils"

const KINDS: { value: AiTrackKind; fr: string; en: string }[] = [
  { value: "skills", fr: "Compétence professionnelle", en: "Professional skill" },
  { value: "programming", fr: "Programmation / technologie", en: "Programming / technology" },
  { value: "language", fr: "Langue", en: "Language" },
]

export function AdminAiCourses({ tracks }: { tracks: AiTrackView[] }) {
  const { t, locale } = useI18n()
  const fr = locale === "fr"
  const router = useRouter()
  const [pending, start] = useTransition()
  const [error, setError] = useState<string | null>(null)
  const [notice, setNotice] = useState<string | null>(null)
  const [coverVersion, setCoverVersion] = useState<Record<string, number>>({})

  function create(form: FormData) {
    setError(null)
    setNotice(null)
    start(async () => {
      const res = await createAiCourseAction(Object.fromEntries(form))
      if (!res.ok) return setError(res.error)
      setNotice(fr ? "Cours généré par l'IA et publié dans Linko Academy." : "Course generated by AI and published in Linko Academy.")
      router.refresh()
    })
  }

  function run(action: () => Promise<{ ok: boolean; error?: string }>) {
    setError(null)
    start(async () => {
      const res = await action()
      if (!res.ok) return setError(res.error ?? "Error")
      router.refresh()
    })
  }

  return (
    <DashboardShell nav={adminNav} titleKey="nav.academy">
      <Panel title={fr ? "Ajouter un cours IA" : "Add an AI course"} icon={Sparkles}>
        <p className="mb-4 text-sm text-muted-foreground">
          {fr
            ? `Saisissez le nom du cours : l'IA rédige un programme professionnel (modules, objectifs), le Tuteur l'enseigne, et l'apprenant reçoit un certificat après l'examen final. Prix : $${AI_COURSE_PRICE_USD} par cours, payé par tous les apprenants, formateurs compris.`
            : `Enter the course name: the AI writes a professional syllabus (modules, outcomes), the Tutor teaches it, and learners get a certificate after the final exam. Price: $${AI_COURSE_PRICE_USD} per course, paid by every learner, teachers included.`}
        </p>
        <form action={create} className="grid gap-4 md:grid-cols-2">
          <div className="md:col-span-2">
            <Field label={fr ? "Nom du cours" : "Course name"} htmlFor="ai-name">
              <Input id="ai-name" name="name" required minLength={2} maxLength={80} placeholder={fr ? "ex. Marketing digital, Comptabilité OHADA, React" : "e.g. Digital marketing, Project management, React"} />
            </Field>
          </div>
          <Field label={fr ? "Type" : "Type"} htmlFor="ai-kind">
            <select id="ai-kind" name="kind" className={selectClass}>
              {KINDS.map((k) => (
                <option key={k.value} value={k.value}>
                  {fr ? k.fr : k.en}
                </option>
              ))}
            </select>
          </Field>
          <Field label={t("common.level")} htmlFor="ai-level">
            <select id="ai-level" name="level" className={selectClass}>
              {(["beginner", "intermediate", "advanced"] as const).map((l) => (
                <option key={l} value={l}>
                  {t(`common.${l}`)}
                </option>
              ))}
            </select>
          </Field>
          <div className="md:col-span-2">
            <Field label={fr ? "Consignes pour l'IA (facultatif)" : "Instructions for the AI (optional)"} htmlFor="ai-notes">
              <Textarea id="ai-notes" name="notes" maxLength={500} className="min-h-16" placeholder={fr ? "Public visé, outils à couvrir, contexte local…" : "Target audience, tools to cover, local context…"} />
            </Field>
          </div>
          <div className="flex items-center justify-end gap-3 md:col-span-2">
            <FormError message={error} />
            <Button type="submit" disabled={pending}>
              {pending ? <Loader2 className="size-4 animate-spin" /> : <Sparkles className="size-4" />}
              {pending ? (fr ? "Génération…" : "Generating…") : fr ? "Générer avec l'IA" : "Generate with AI"}
            </Button>
          </div>
        </form>
        {notice && <p className="mt-4 rounded-lg bg-[#064E3B]/5 px-4 py-2.5 text-sm text-[#064E3B] dark:bg-emerald-950/40 dark:text-emerald-300">{notice}</p>}
      </Panel>

      <ul className="mt-6 grid gap-5 lg:grid-cols-2">
        {tracks.map((track) => (
          <li key={track.slug} className={cn("flex flex-col overflow-hidden rounded-2xl border border-border bg-card", track.hidden && "opacity-60")}>
            {/* key changes after regeneration so the new picture is fetched */}
            <TrackCover key={`${track.slug}-${coverVersion[track.slug] ?? 0}`} track={track} version={coverVersion[track.slug]} className="aspect-[21/9]" />
            <header className="flex items-start gap-3 border-b border-border p-4">
              <span className="flex h-10 min-w-10 shrink-0 items-center justify-center rounded-xl bg-[#064E3B]/10 px-2 font-mono text-xs font-bold text-[#064E3B] dark:bg-emerald-950/50 dark:text-emerald-400">
                <TrackMark track={track} logoClassName="size-6" />
              </span>
              <div className="min-w-0 flex-1">
                <h3 className="font-medium leading-snug">{localize(track.name, locale)}</h3>
                <div className="mt-1 flex flex-wrap gap-1.5">
                  <Badge variant="secondary">{fr ? KINDS.find((k) => k.value === track.kind)?.fr : KINDS.find((k) => k.value === track.kind)?.en}</Badge>
                  {track.custom ? <Badge variant="secondary">{fr ? "Généré par l'IA" : "AI-generated"}</Badge> : <Badge variant="secondary">{fr ? "Intégré" : "Built-in"}</Badge>}
                  {track.hidden && <Badge variant="secondary">{fr ? "Masqué" : "Hidden"}</Badge>}
                </div>
              </div>
            </header>
            {track.description && <p className="px-4 pt-3 text-sm text-muted-foreground">{localize(track.description, locale)}</p>}
            <ol className="flex-1 space-y-1 p-4 text-sm">
              {track.modules.map((m, i) => (
                <li key={i} className="flex gap-2">
                  <span className="w-5 shrink-0 text-muted-foreground tabular-nums">{i + 1}.</span>
                  <span>
                    {localize(m.title, locale)}
                    <span className="block text-xs text-muted-foreground">{m.focus}</span>
                  </span>
                </li>
              ))}
            </ol>
            <footer className="flex gap-2 border-t border-border p-4">
              <Button size="sm" variant="outline" className="flex-1" render={<Link href={`/academy/${aiModuleSlug(track.slug, 1)}`} />}>
                <Bot className="size-4" />
                {fr ? "Prévisualiser" : "Preview"}
              </Button>
              <Button
                size="sm"
                variant="outline"
                disabled={pending}
                aria-label={fr ? "Nouvelle image" : "New cover"}
                title={fr ? "Générer une nouvelle image" : "Generate a new cover"}
                onClick={() =>
                  run(async () => {
                    const res = await regenerateAiCoverAction(track.slug)
                    if (res.ok) setCoverVersion((v) => ({ ...v, [track.slug]: (v[track.slug] ?? 0) + 1 }))
                    return res
                  })
                }
              >
                <ImagePlus className="size-4" />
              </Button>
              {track.custom && (
                <>
                  <Button
                    size="sm"
                    variant="outline"
                    disabled={pending}
                    aria-label={track.hidden ? "Publish" : "Hide"}
                    onClick={() => run(() => setAiCourseVisibilityAction({ slug: track.slug, hidden: !track.hidden }))}
                  >
                    {track.hidden ? <Eye className="size-4" /> : <EyeOff className="size-4" />}
                  </Button>
                  <Button
                    size="sm"
                    variant="outline"
                    disabled={pending}
                    aria-label={fr ? "Supprimer" : "Delete"}
                    onClick={() => {
                      if (confirm(fr ? "Supprimer ce cours ?" : "Delete this course?")) run(() => deleteAiCourseAction(track.slug))
                    }}
                  >
                    <Trash2 className="size-4" />
                  </Button>
                </>
              )}
            </footer>
          </li>
        ))}
      </ul>
    </DashboardShell>
  )
}
